// The app's copies of the eyes: the module its components draw from, and the region of its stylesheet that sizes
// and moves the loader. Both go through Biome's formatter, so `bun run check` and `bun run format` find them as
// they are written; a test gives a formatter of its own.
import { biome, constant, type Formatter } from "./format.ts";
import { markParts } from "./icon.ts";
import { LOADER, loaderCss } from "./loader.ts";
import { COLOURS, MARK } from "./numbers.ts";
import { WORDMARK_SHAPES } from "./wordmark.ts";

/** The module `Mark`, `Eyes` and the GitHub avatar's icon take their numbers from. */
export const EYES_MODULE = "apps/web/src/ui/eyes.generated.ts";
/** The app's stylesheet, with the loader's region in it. */
export const STYLESHEET = "apps/web/src/styles/system.css";

/** The text of the app's module of the eyes, as `format` (Biome's unless given) shapes it. */
export function eyesModule(format: Formatter = biome): Promise<string> {
  const solid = markParts(true);
  const ring = markParts(false);
  const { centres, cy, eye, ring: thickness, ringRadius, dot, hole, box } = LOADER;
  return format(
    EYES_MODULE,
    [
      "// Generated by `bun run brand` from @lookover/brand, the eyes' one source (ADR 0063): never edit by hand.",
      "",
      constant(
        "The mark on its square `grid`: the solid eyes, the ring eyes and their pupils (evenodd), and its two lines.",
        "MARK",
        {
          grid: MARK.grid,
          solid: solid.eyes,
          ring: ring.eyes,
          pupils: ring.pupils,
          lines: {
            x: solid.x0,
            y1: solid.y1,
            y2: solid.y2,
            width1: solid.span,
            width2: solid.span2,
            height: solid.h,
          },
        },
      ),
      constant(
        "The icon's tile and the file's fixed colours: the GitHub avatar stands for GitHub's image of it.",
        "ICON_TILE",
        { rx: MARK.tileRx, tile: COLOURS.ink, eyes: COLOURS.paper, accent: COLOURS.accent },
      ),
      constant(
        "The loader on its box: the eyes, the ring's thickness and its stroke's radius, the dot and the hole.",
        "LOADER",
        {
          width: box.drawing.width,
          height: box.drawing.height,
          centres,
          cy,
          eye,
          ring: thickness,
          ringRadius,
          dot,
          hole,
        },
      ),
      constant(
        "The wordmark's drawing box, its files' `viewBox`: the simulated GitHub page sizes it from it.",
        "WORDMARK_BOX",
        { width: WORDMARK_SHAPES.view.width, height: WORDMARK_SHAPES.view.height },
      ),
    ].join("\n"),
  );
}

const BEGIN = [
  "/* Written by `bun run brand` from @lookover/brand (ADR 0063): the loader's box, its rest and its reading.",
  "   Never edit by hand. */",
].join("\n");
const BEGINS = "/* Written by `bun run brand`";
const END = "/* End of what `bun run brand` writes. */";

/**
 * The app's stylesheet: `current` with the region between its two markers rendered from the source, the whole
 * file as `format` (Biome's unless given) shapes it. An empty `current` (no stylesheet yet) is the region alone.
 */
export async function appStylesheet(current: string, format: Formatter = biome): Promise<string> {
  const region = `${BEGIN}\n${loaderCss()}${END}\n`;
  if (current === "") return format(STYLESHEET, region);
  const start = current.indexOf(BEGINS);
  const end = current.indexOf(END, start);
  if (start < 0 || end < 0) {
    throw new Error(
      `${STYLESHEET} has lost the region \`bun run brand\` writes: put back its two marker comments, then run \`bun run brand\`.`,
    );
  }
  const after = current.slice(end + END.length).replace(/^\n/, "");
  return format(STYLESHEET, `${current.slice(0, start)}${region}${after}`);
}
