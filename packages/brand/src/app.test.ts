// The app's two generated copies: the module its components draw the eyes from, and the region of its
// stylesheet that sizes and moves the loader. Both come out as Biome formats them, and a hand edit of either
// fails the check, naming the file.
import { afterEach, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { appStylesheet, driftedCopies, EYES_MODULE, eyesModule, STYLESHEET, writeCopies } from "./index.ts";

const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** A new empty folder standing for a checkout without docs/, removed after the test. */
function checkout(): string {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "lookover-brand-app-")));
  dirs.push(dir);
  return dir;
}

const BEGIN =
  "/* Written by `bun run brand` from @lookover/brand (ADR 0063): the loader's box, its rest and its";

test("the module carries the mark, the icon's tile and the loader, and says it is generated", () => {
  const text = eyesModule();
  expect(text.startsWith("// Generated by `bun run brand` from @lookover/brand")).toBe(true);
  expect(text).toContain("never edit by hand");
  expect(text).toContain("export const MARK = {\n  grid: 64,\n");
  expect(text).toContain(
    '"M10 21.25a9.4 9.4 0 1 0 18.8 0a9.4 9.4 0 1 0 -18.8 0zM15.6 23.48a3.8 4.23 0 1 0 7.6 0',
  );
  expect(text).toContain("export const ICON_TILE = {");
  expect(text).toContain('{ rx: 14.4, tile: "#16130F", eyes: "#F7F6F2", accent: "#E5347B" }');
  expect(text).toContain("export const LOADER = {");
  expect(text).toContain("centres: [13.67, 50.33],");
  expect(text).toContain("hole: { rx: 5.53, ry: 6.15 },");
});

test("the stylesheet's region is the loader's box and motion, and the rest of the file is kept", () => {
  const current = [
    ".before {",
    "  color: red;",
    "}",
    BEGIN,
    "   long gone */",
    ".eyes { height: 1em }",
    "/* End of what `bun run brand` writes. */",
    ".after {",
    "  color: blue;",
    "}",
    "",
  ].join("\n");
  const css = appStylesheet(current);
  expect(css.startsWith(".before {\n  color: red;\n}\n/* Written by `bun run brand`")).toBe(true);
  expect(css.endsWith("/* End of what `bun run brand` writes. */\n.after {\n  color: blue;\n}\n")).toBe(true);
  expect(css).toContain(".eyes {\n  width: 1.2em;\n  height: 0.825em;\n  vertical-align: -0.0625em;\n}\n");
  expect(css).toContain(".eyes.lg {\n  width: 48px;\n  height: 33px;\n}\n");
  expect(css).toContain(".eyes .p {\n  transform: translateY(3.85px);\n}\n");
  expect(css).not.toContain("1em }");
  expect(appStylesheet(css)).toBe(css);
});

test("a stylesheet without the region is refused, naming it", () => {
  expect(() => appStylesheet(".a {\n  color: red;\n}\n")).toThrow(
    `${STYLESHEET} has lost the region \`bun run brand\` writes`,
  );
});

test("a hand edit of the module or of the stylesheet's region fails, naming the file", () => {
  const root = checkout();
  writeCopies(root);
  expect(driftedCopies(root)).toEqual([]);
  const module = join(root, EYES_MODULE);
  writeFileSync(module, readFileSync(module, "utf8").replace("rx: 14.4,", "rx: 12,"));
  const css = join(root, STYLESHEET);
  writeFileSync(css, readFileSync(css, "utf8").replace("height: 0.825em;", "height: 1em;"));
  expect(driftedCopies(root)).toEqual([
    `${EYES_MODULE} is not what the source draws: run \`bun run brand\`.`,
    `${STYLESHEET} is not what the source draws: run \`bun run brand\`.`,
  ]);
});
