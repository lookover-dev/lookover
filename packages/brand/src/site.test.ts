/** A style rule of `css`: its selectors, its declarations and the `@media` it sits in, if any. */
type Rule = { media: string | null; selectors: string[]; body: string };

/** The style rules of `css` in order, keyframes' stops left out. */
function styleRules(css: string): Rule[] {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const open: { prelude: string; start: number }[] = [];
  const out: Rule[] = [];
  for (const m of text.matchAll(/([^{}]*)\{|\}/g)) {
    if (m[0] !== "}") {
      open.push({ prelude: (m[1] ?? "").trim(), start: (m.index ?? 0) + m[0].length });
      continue;
    }
    const block = open.pop();
    if (!block || block.prelude.startsWith("@")) continue;
    if (open.some((b) => b.prelude.startsWith("@keyframes"))) continue;
    const media = open.findLast((b) => b.prelude.startsWith("@media"))?.prelude ?? null;
    const selectors = block.prelude.split(",").map((s) => s.trim());
    out.push({ media, selectors, body: text.slice(block.start, m.index) });
  }
  return out;
}

const NO_PREFERENCE = "@media (prefers-reduced-motion: no-preference)";
const REDUCE = "@media (prefers-reduced-motion: reduce)";
const animates = (r: Rule) => /animation:(?!\s*none)/.test(r.body);

/**
 * The selectors that animate under reduced motion: those of a rule that animates outside the no-preference block,
 * unless a later rule in the reduce block stops it with the same selector (as specific, and later, so it wins).
 */
function movingUnderReducedMotion(css: string): string[] {
  const all = styleRules(css);
  return all.flatMap((r, i) =>
    !animates(r) || r.media === NO_PREFERENCE
      ? []
      : r.selectors.filter(
          (s) =>
            !all
              .slice(i + 1)
              .some((o) => o.media === REDUCE && /animation:\s*none/.test(o.body) && o.selectors.includes(s)),
        ),
  );
}

test("under reduced motion nothing moves: every animation plays only with no preference, or is stopped", async () => {
  const css = await siteStylesheet(format);
  expect(styleRules(css).filter(animates).length).toBeGreaterThanOrEqual(5);
  expect(movingUnderReducedMotion(css)).toEqual([]);
  // The check catches a stop that loses: a state's blink (0,3,0) stopped by `.mark .lid` (0,2,0) still plays.
  const losing = [
    '.mark[data-state="idle"] .lid {\n  animation: mark-blink 6s infinite;\n}',
    `${REDUCE} {\n  .mark .lid {\n    animation: none;\n  }\n}`,
  ].join("\n");
  expect(movingUnderReducedMotion(losing)).toEqual(['.mark[data-state="idle"] .lid']);
});

test("a hand edit of the site's module, stylesheet or favicon fails, naming the file", async () => {
  const root = checkout();
  await writeCopies(root, { format });
  expect(await driftedCopies(root, { format })).toEqual([]);
  for (const [path, from, to] of [
    // The full-bleed favicon rounded again by hand.
    [SITE_FAVICON, 'height="64" fill', 'height="64" rx="14.4" fill'],
    [SITE_MODULE, "-174.05", "-174"],
    [SITE_STYLESHEET, "scaleY(0.84)", "scaleY(0.8)"],
  ] as const) {
    const file = join(root, path);
    writeFileSync(file, readFileSync(file, "utf8").replace(from, to));
  }
  const run = "run `bun run brand`";
  expect(await driftedCopies(root, { format })).toEqual([
    `${SITE_FAVICON} is not what the source draws: ${run}.`,
    `${SITE_MODULE} is not what the source draws: ${run}.`,
    `${SITE_STYLESHEET} is not what the source draws: ${run}.`,
  ]);
});
