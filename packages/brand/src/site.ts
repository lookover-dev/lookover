// The site's copies of the eyes (ADR 0064, 4): its favicon, the module its pages and scripts draw the eyes from,
// and the stylesheet that shows each drawing in its theme and moves the loader and the mark's states. The module
// holds the drawings as SVG text with `{id}` where their masks' ids go and `{state}` where the mark's state goes,
// and functions that fill them in, so it runs in Astro and in the browser alike and imports nothing. Both go
// through Biome's formatter.
import { addressableLoader, addressableWordmark, markText } from "./addressable.ts";
import { rule } from "./css.ts";
import { constant, formatted } from "./format.ts";
import { icon } from "./icon.ts";
import { loaderCss } from "./loader.ts";
import { COLOURS } from "./numbers.ts";
import { GAZE, MARK_STATES, markStatesCss } from "./states.ts";

/** The site's favicon: the icon, as the app's is. */
export const SITE_FAVICON = "apps/site/public/favicon.svg";
/** The module the site's pages and scripts draw the eyes from. */
export const SITE_MODULE = "apps/site/src/brand/eyes.generated.ts";
/** The stylesheet that shows the drawings in their theme and moves them. */
export const SITE_STYLESHEET = "apps/site/src/brand/eyes.generated.css";

const { ink, paper, accent } = COLOURS;

/** The icon as its file draws it: the favicon, the GitHub avatar and the check's icon. */
export const siteIcon = () => icon(ink, paper, accent, true);

const ID = "{id}";
const STATE = "{state}";

/** The text of the site's module of the eyes, as Biome formats it. */
export function siteModule(): string {
  const text = (doc: string, name: string, svg: string) =>
    `/** ${doc} */\nconst ${name} = ${JSON.stringify(svg)};\n`;
  return formatted(
    SITE_MODULE,
    [
      "// Generated by `bun run brand` from @lookover/brand (ADR 0063, ADR 0064): never edit by hand.",
      "// The drawings as SVG text, every part the site's scripts and `eyes.generated.css` address named by a class;",
      "// `id` starts the ids of a drawing's masks, so give each drawing on a page its own.",
      "",
      constant("The mark's states, set as `data-state` on its `svg`.", "MARK_STATES", MARK_STATES),
      "export type MarkState = (typeof MARK_STATES)[number];",
      "",
      constant(
        "Where each pupil looks, as offsets from where its drawing rests it (straight down), in the drawing's units: the wordmark's (font units) and the mark's (its 64 grid), the solid eye's `.hole` and the ring eye's `.pupil`.",
        "GAZE",
        GAZE,
      ),
      text("The wordmark.", "WORDMARK", addressableWordmark(ID)),
      text("The mark.", "MARK", markText(ID, STATE)),
      text("The loader, reading.", "EYES", addressableLoader(ID, false)),
      text("The loader, still.", "EYES_STILL", addressableLoader(ID, true)),
      constant(
        "The icon as its file draws it, in its own colours: the GitHub avatar and the check's icon.",
        "ICON",
        siteIcon(),
      ),
      "/**",
      " * The wordmark: `.letter.letter-l` … `.letter-r`; two `.eye`s (`data-eye`), each `.eye-solid` with its",
      " * `.hole` and `.lid`, and `.eye-ring` with its `.pupil` and `.lid`; the `.chunk`s, `data-i` 0 to 4, the",
      " * accent one also `.chunk-acc`.",
      " */",
      "export function wordmark(id: string): string {",
      `  return WORDMARK.replaceAll("${ID}", id);`,
      "}",
      "",
      "/** The mark in `state`: two `.eye`s as the wordmark's, and the lines `.line.line-1` (accent) and `.line-2`. */",
      'export function mark(id: string, state: MarkState = "idle"): string {',
      `  return MARK.replaceAll("${ID}", id).replaceAll("${STATE}", state);`,
      "}",
      "",
      "/** The loader in its `span.eyes`: the holes `.h` and the dots `.p` read unless `still`. */",
      "export function eyes(id: string, still = false): string {",
      `  return (still ? EYES_STILL : EYES).replaceAll("${ID}", id);`,
      "}",
      "",
    ].join("\n"),
  );
}

/** The text of the site's stylesheet of the eyes, as Biome formats it. */
export function siteStylesheet(): string {
  const light = ':root[data-theme="light"]';
  const solid = [".wordmark .eye-solid", ".mark .eye-solid", ".eyes .e-solid"];
  const ring = [".wordmark .eye-ring", ".mark .eye-ring", ".eyes .e-ring"];
  const lines = [
    "/* Generated by `bun run brand` from @lookover/brand (ADR 0063, ADR 0064): never edit by hand.",
    "   Solid eyes light on dark, ring eyes dark on light; the accent; the loader's box, rest and reading; the",
    "   mark's states, from its `data-state`, their loops only with no reduced-motion preference; the loader's,",
    "   the app's own, stopped under reduced motion by its own selectors, later. */",
    ...rule(ring, ["display: none;"]),
    ...rule(
      solid.map((s) => `${light} ${s}`),
      ["display: none;"],
    ),
    ...rule(
      ring.map((s) => `${light} ${s}`),
      ["display: inline;"],
    ),
    ...rule([".wordmark .chunk-acc", ".mark .line-1"], ["fill: var(--acc);"]),
    ...rule([".eyes"], ["display: inline-block;"]),
    ...rule([".eyes svg"], ["width: 100%;", "height: 100%;", "display: block;", "overflow: visible;"]),
    loaderCss().trimEnd(),
    markStatesCss().trimEnd(),
    "@media (prefers-reduced-motion: reduce) {",
    ...rule([".eyes .p.read", ".eyes .h.read"], ["animation: none;"], "  "),
    "}",
  ];
  return formatted(SITE_STYLESHEET, `${lines.join("\n")}\n`);
}
