// `bun run build`: the program as one file (ADR 0054, "Packaging, nothing published"). It builds the web app for
// the program (`apps/web` `build:program`, into `apps/web/dist`), generates the compiled binary's entry,
// `dist/build/lookover.ts` (every file of that build imported as a file the binary carries, then `main.ts`'s `main`
// run as the binary), compiles it with `bun build --compile` into `dist/lookover` (`lookover.exe` on Windows), then
// checks it: a copy of it, out of the clone, answers `--version`, renders the loop's skill as the clone does
// (`--skill`), and serves a fresh data folder in demo mode with every migration applied, the app's page and its
// script, and stops when asked. The generated entry is in `dist/`, which Git, `tsc`, knip and Biome leave out, so a
// clone that never built checks green. Nothing is signed, uploaded or put on the PATH. `--baseline` (ADR 0061, the
// release's x64 executables) compiles for Bun's `-baseline` build of this machine's target; nothing else changes.

import { Database } from "bun:sqlite";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { API, APP_FLOW } from "@lookover/contracts";
import { renderSkill, SKILL_NAME, skillCommandLine, skillStampOf, VERSION } from "@lookover/service";

const root = resolve(import.meta.dir, "..");
const WEB = join(root, "apps", "web");
const WEB_DIST = join(WEB, "dist");
/** What the service's stand-alone pages carry from the web app (`apps/web/src/standalone.ts`). */
const SYSTEM_CSS = join(WEB, "src", "styles", "system.css");
const FAVICON = join(WEB, "public", "favicon.svg");
const SERVICE_SRC = join(root, "apps", "service", "src");
const MIGRATIONS = join(root, "packages", "store", "src", "migrations");
const DIST = join(root, "dist");
const ENTRY = join(DIST, "build", "lookover.ts");
const BINARY = join(DIST, process.platform === "win32" ? "lookover.exe" : "lookover");
/** Lookover's one version (ADR 0061), read off the disk: the binary must say it, whatever its build inlined. */
const ROOT_VERSION: unknown = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
/** How long the binary may take to start in demo mode, or to stop once asked, before the check fails. */
const LIMIT_MS = 30_000;

/** The files of the built app in `dist`, by their path in it, with forward slashes, in name order. */
export function webFilesIn(dist: string): string[] {
  const files = readdirSync(dist, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dist, join(entry.parentPath, entry.name)).replaceAll("\\", "/"))
    .sort();
  if (!files.includes("index.html")) throw new Error(`${dist} has no index.html: the web app wasn't built`);
  return files;
}

/**
 * The compiled binary's entry for the built app's `files`: `paths` are where the app's build (`web`) and the
 * service's source (`service`) are, from the entry's folder.
 */
export function entryModule(files: string[], paths: { web: string; service: string }): string {
  const imports = files.map(
    (file, i) => `import f${i} from ${JSON.stringify(`${paths.web}/${file}`)} with { type: "file" };\n`,
  );
  const map = files.map((file, i) => `  [${JSON.stringify(file)}, f${i}],\n`);
  return (
    "// Generated by `bun run build` (scripts/build.ts): the compiled binary's entry. Never edited, never committed.\n" +
    `import { main } from "${paths.service}/main.ts";\n` +
    `import { programSelf } from "${paths.service}/self.ts";\n` +
    `import { carriedWebFiles } from "${paths.service}/web-files.ts";\n` +
    imports.join("") +
    `\nawait main(programSelf(process.execPath, process.env, carriedWebFiles(new Map<string, string>([\n${map.join("")}]))));\n`
  );
}

/** Bun's name for each platform in a compile target (`bun-<os>-<arch>`). */
const TARGET_OS: Partial<Record<NodeJS.Platform, string>> = {
  win32: "windows",
  linux: "linux",
  darwin: "darwin",
};

/**
 * The compile's target: this machine's, unless `baseline` (`--baseline`, ADR 0061) asks for Bun's `-baseline` build of
 * it, which runs on x64 processors without AVX2 too, so an older one doesn't stop with "Illegal instruction". Only x64
 * has one.
 */
export function targetArgs(o: { baseline: boolean; platform: NodeJS.Platform; arch: string }): string[] {
  if (!o.baseline) return [];
  if (o.arch !== "x64") throw new Error(`--baseline is for x64; this machine is ${o.arch}`);
  const os = TARGET_OS[o.platform];
  if (os === undefined) throw new Error(`Bun compiles for no ${o.platform}`);
  return [`--target=bun-${os}-x64-baseline`];
}

/** Runs `cmd` in `cwd`; throws with what it printed when it fails. */
async function run(cmd: string[], cwd: string): Promise<string> {
  const proc = Bun.spawn(cmd, { cwd, stdout: "pipe", stderr: "pipe" });
  const [code, said, failed] = await Promise.all([
    proc.exited,
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
  ]);
  if (code !== 0) throw new Error(`${cmd.join(" ")} exited ${code}:\n${said}${failed}`);
  return said;
}

const posix = (path: string) => path.replaceAll("\\", "/");

/** The web app for the program, the entry over it, then the binary. */
async function build(target: string[]): Promise<void> {
  await run([process.execPath, "run", "build:program", "--logLevel", "error"], WEB);
  const files = webFilesIn(WEB_DIST);
  mkdirSync(join(ENTRY, ".."), { recursive: true });
  const from = join(ENTRY, "..");
  writeFileSync(
    ENTRY,
    entryModule(files, { web: posix(relative(from, WEB_DIST)), service: posix(relative(from, SERVICE_SRC)) }),
  );
  // Run in `dist`, so the compile's scratch file (`.*.bun-build`) lands there, not in the clone's root.
  await run([process.execPath, "build", "--compile", ...target, ENTRY, "--outfile", BINARY], DIST);
  console.log(`Built ${relative(root, BINARY)}, carrying the web app's ${files.length} files.`);
}

/** Fails the check with `why`. */
function failed(why: string): never {
  throw new Error(`The binary failed its check: ${why}`);
}

/** Waits for `done` every 50 ms, up to `LIMIT_MS`; whether it came. */
async function waitFor(done: () => boolean): Promise<boolean> {
  for (let waited = 0; waited < LIMIT_MS && !done(); waited += 50) await Bun.sleep(50);
  return done();
}

/** The names of the migrations applied in the store of the one demo room in the data folder `home`. */
function appliedIn(home: string): string[] {
  const rooms = readdirSync(join(home, "rooms"));
  if (rooms.length !== 1) failed(`demo mode left ${rooms.length} rooms in its data folder, not one`);
  const db = new Database(join(home, "rooms", rooms[0] ?? "", "lookover.sqlite"), { readonly: true });
  try {
    return db
      .query<{ name: string }, []>("SELECT name FROM migrations ORDER BY name")
      .all()
      .map((row) => row.name);
  } finally {
    db.close();
  }
}

/** The page and the script it loads, as the binary serves them, against the build's own. */
async function checkServed(origin: string): Promise<void> {
  const page = await fetch(`${origin}/`);
  const html = await page.text();
  if (page.status !== 200 || html !== (await Bun.file(join(WEB_DIST, "index.html")).text()))
    failed(`its page answered ${page.status}, not the built index.html`);
  const script = /src="\/(assets\/[^"]+\.js)"/.exec(html)?.[1] ?? failed("its page loads no script");
  const served = await fetch(`${origin}/${script}`);
  const bytes = (await served.arrayBuffer()).byteLength;
  if (served.status !== 200 || bytes !== Bun.file(join(WEB_DIST, script)).size)
    failed(`its ${script} answered ${served.status} with ${bytes} bytes, not the built file`);
  // The tab GitHub returns to (ADR 0058): a stand-alone page, the design system's stylesheet and the eyes in it.
  const installed = await fetch(`${origin}${APP_FLOW.installed}`);
  const standalone = await installed.text();
  const [style, eyes] = await Promise.all([Bun.file(SYSTEM_CSS).text(), Bun.file(FAVICON).text()]);
  if (installed.status !== 200 || !standalone.includes(style) || !standalone.includes(eyes))
    failed(`its installed page answered ${installed.status} without system.css and favicon.svg in it`);
}

/**
 * Removes the folder `dir`, retrying while Windows still holds the new exe (an antivirus scanning it); whether it
 * went. A folder left behind doesn't fail the check: the caller says where it is.
 */
function removed(dir: string): boolean {
  try {
    rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
    return true;
  } catch {
    return false;
  }
}

/**
 * The binary, copied out of the clone into a scratch folder and run there: its version, then demo mode on a fresh
 * data folder, its snapshot, its page and script, then asked to stop, then every migration applied in its store.
 */
async function check(): Promise<void> {
  // Its long name, never a Windows short one (`DELLXP~1`): the copy knows itself by it, and its skill names it.
  const scratch = realpathSync.native(mkdtempSync(join(tmpdir(), "lookover-binary-")));
  const copy = join(scratch, BINARY.slice(DIST.length + 1));
  try {
    copyFileSync(BINARY, copy);
    const version = (await run([copy, "--version"], scratch)).trim();
    if (version !== ROOT_VERSION || version !== VERSION)
      failed(`--version said "${version}", not the root package.json's ${String(ROOT_VERSION)}`);
    const home = join(scratch, "home");
    // The skill it installs (ADR 0058), rendered by the copy (`--skill`): the clone's `SKILL.md`, carried whole and
    // never read from a clone, with the copy's own command and version in it, byte for byte as the clone renders it.
    const skill = await run([copy, "--skill", `--home=${home}`], scratch);
    const words = [copy, `--home=${home}`].map((word) => (process.platform === "win32" ? posix(word) : word));
    const expected = renderSkill({ name: SKILL_NAME, command: skillCommandLine(words), version: VERSION });
    if (skill !== `${expected}\n`)
      failed(
        `its skill isn't the clone's SKILL.md rendered for it: its stamp says ${JSON.stringify(skillStampOf(skill))}`,
      );

    const announce = join(scratch, "service.json");
    const proc = Bun.spawn([copy, "serve", "--demo", `--home=${home}`, `--announce=${announce}`], {
      cwd: scratch,
      stdout: "ignore",
      stderr: "pipe",
    });
    // Read as it comes, so a service that says much never waits on a full pipe.
    const printed = new Response(proc.stderr).text();
    try {
      if (
        !(await waitFor(() => Bun.file(announce).size > 0 || proc.exitCode !== null)) ||
        proc.exitCode !== null
      ) {
        proc.kill();
        failed(`it didn't serve in demo mode: ${await printed}`);
      }
      const { origin, openUrl } = await Bun.file(announce).json();
      const opened = await fetch(openUrl, { redirect: "manual" });
      const cookie = opened.headers.get("set-cookie")?.split(";")[0] ?? failed("its link set no cookie");
      const headers = { cookie, origin };
      const snapshot = await fetch(`${origin}${API.snapshot}`, { headers });
      const said =
        snapshot.status === 200 ? await snapshot.json() : failed(`its snapshot answered ${snapshot.status}`);
      if (said.service?.version !== VERSION) failed(`its snapshot says version ${said.service?.version}`);
      await checkServed(origin);
      const stop = await fetch(`${origin}${API.stop}`, { method: "POST", headers });
      if (stop.status !== 200) failed(`asked to stop, it answered ${stop.status}`);
      if (!(await waitFor(() => proc.exitCode !== null))) failed("asked to stop, it ran on");
      if (proc.exitCode !== 0) failed(`it stopped with exit code ${proc.exitCode}`);
    } finally {
      proc.kill();
      await proc.exited;
    }

    const migrations = readdirSync(MIGRATIONS)
      .map((file) => file.replace(/\.sql$/, ""))
      .sort();
    const applied = appliedIn(home);
    if (applied.join() !== migrations.join())
      failed(`its store applied ${applied.length} migrations, the store has ${migrations.length}`);
    console.log(
      `Checked a copy out of the clone: version ${VERSION}, the skill rendered as the clone does, demo mode served the app, ${applied.length} migrations applied, stopped.`,
    );
  } finally {
    if (!removed(scratch)) console.log(`Left the check's scratch folder ${scratch}: it couldn't be removed.`);
  }
}

if (import.meta.main) {
  const unread = process.argv.slice(2).filter((arg) => arg !== "--baseline");
  if (unread.length > 0) {
    console.error(`bun run build reads only --baseline, not ${unread.join(" ")}`);
    process.exit(2);
  }
  const baseline = process.argv.includes("--baseline");
  await build(targetArgs({ baseline, platform: process.platform, arch: process.arch }));
  await check();
}
