// `bun run migrations`: writes the store's embedded list of migrations, packages/store/src/embedded-migrations.ts,
// from its `src/migrations/` folder (I-165): one text import per `.sql` file, then the list in name order, so a
// bundled or compiled service carries them. Run it after adding, removing or renaming a migration; the store's
// tests fail while the list misses one, and scripts/migrations.test.ts while the module differs from what this
// writes. The text goes through Biome's formatter, so the module is as `bun run check` wants it whatever a
// migration's name. This reads the folder itself and imports of the store only its name rule (a second entry that
// imports nothing), so it runs while the list is stale.
import { readdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { MIGRATION_FILE as NAME } from "@lookover/store/migration-name";
import { spawnSync } from "bun";

const root = resolve(import.meta.dir, "..");
const STORE = join(root, "packages", "store", "src");
/** The store's own migrations, the folder the list is made from. */
const MIGRATIONS = join(STORE, "migrations");
/** The generated module that embeds them. */
export const EMBEDDED_MIGRATIONS = join(STORE, "embedded-migrations.ts");

/** `text`, formatted by Biome as the module's own file would be. */
function formatted(text: string): string {
  const biome = Bun.which("biome", { PATH: join(root, "node_modules", ".bin") });
  if (!biome) throw new Error("biome is not installed: run bun install");
  const done = spawnSync([biome, "format", `--stdin-file-path=${relative(root, EMBEDDED_MIGRATIONS)}`], {
    cwd: root,
    stdin: new TextEncoder().encode(text),
    stdout: "pipe",
    stderr: "pipe",
  });
  if (done.exitCode !== 0) throw new Error(`biome format failed: ${done.stderr.toString()}`);
  return done.stdout.toString();
}

/**
 * The text of `embedded-migrations.ts` for the migrations of `folder` (the store's own unless a test names
 * another), as Biome formats it. A file there not named as a migration is refused.
 */
export function migrationsModule(folder: string = MIGRATIONS): string {
  const files = readdirSync(folder)
    .sort()
    .map((file) => {
      const name = NAME.exec(file)?.[1];
      if (name === undefined) throw new Error(`${file} in ${folder} is not named YYYYMMDDHHMMSS-<what>.sql`);
      return { file, name };
    });
  const imports = files.map(
    ({ file }, i) => `import m${i} from "./migrations/${file}" with { type: "text" };\n`,
  );
  const list = files.map(({ name }, i) => `{ name: ${JSON.stringify(name)}, sql: m${i} },\n`);
  return formatted(
    "// Generated by `bun run migrations` (scripts/migrations.ts) from `src/migrations/`: never edit by hand.\n" +
      imports.join("") +
      "\n/** Every migration of `src/migrations/`, in name order, its SQL bundled with the code. */\n" +
      `export const EMBEDDED: { name: string; sql: string }[] = [\n${list.join("")}];\n`,
  );
}

if (import.meta.main) {
  writeFileSync(EMBEDDED_MIGRATIONS, migrationsModule());
  console.log(`Wrote ${relative(root, EMBEDDED_MIGRATIONS)}.`);
}
